-- Dashboard chart schema. Applied to Supabase as dashboard_chart_sources.
-- Existing pickup/bin records are preserved.
begin;

create table if not exists public.contamination_categories (
    id text primary key,
    label text not null unique
);

alter table public.fulfilled_pickups
    add column if not exists service_status text,
    add column if not exists contamination_category_id text
        references public.contamination_categories(id);
create index if not exists fulfilled_pickups_contamination_category_idx
    on public.fulfilled_pickups (contamination_category_id);

-- A stable key makes schedule pagination deterministic, including unmatched services.
alter table public.pickup_schedule_entries
    add column if not exists id bigint generated by default as identity primary key,
    add column if not exists driver_name text;

create table if not exists public.collection_costs (
    id text primary key,
    building_group text not null check (length(trim(building_group)) > 0),
    cost_month date not null check (extract(day from cost_month) = 1),
    amount_cents integer not null check (amount_cents >= 0),
    currency text not null default 'USD' check (currency = 'USD'),
    description text,
    is_demo boolean not null default false
);
create index if not exists collection_costs_building_month_idx
    on public.collection_costs (building_group, cost_month);

-- These two lookup/reporting tables expose read access only to client roles.
-- Leave the project's existing pickup-table access rules unchanged.
alter table public.contamination_categories enable row level security;
alter table public.collection_costs enable row level security;
drop policy if exists dashboard_read_categories on public.contamination_categories;
create policy dashboard_read_categories on public.contamination_categories
    for select to anon, authenticated using (true);
drop policy if exists dashboard_read_costs on public.collection_costs;
create policy dashboard_read_costs on public.collection_costs
    for select to anon, authenticated using (true);
grant select on public.contamination_categories, public.collection_costs to anon, authenticated, service_role;

commit;
